// Boutique de bout en bout contre le serveur local (wrangler dev, secrets de test dans server/.dev.vars) :
// compte créé automatiquement, achat confirmé par un webhook signé avec le secret de test, inventaire, badge,
// équipement d'un camouflage visible sur l'arme, aucun effet sur les statistiques. Aucun appel à Stripe.
import { createHmac } from 'node:crypto';
import { chromium, sleep, SHOTS } from './lib.mjs';
const URL = process.env.WB_ONLINE_URL || 'http://localhost:4174/?autotest';
const API = 'http://localhost:8787';
let pass = 0, fail = 0;
const ok = (c, label, extra = '') => { if (c) pass++; else fail++; console.log(`${c ? 'PASS' : 'FAIL'} ${label} ${extra}`); };
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const errors = [];
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(URL);
await page.waitForFunction(() => window.WB && window.WB.game.state === 'menu', null, { timeout: 120000 });
await page.evaluate(() => window.WB.quality('medium'));
await page.evaluate(() => window.WB.newGame('vanguard', 'Acheteur'));
await page.waitForFunction(() => window.WB.state().level === 'hub' && window.WB.state().state === 'play', null, { timeout: 120000 });
const stats0 = await page.evaluate(() => { const s = window.WB.game.weapons.w.st; return { dmg: s.damage, rpm: s.rpm, spread: s.hipSpread, mag: s.mag }; });
await page.evaluate(() => { window.WB.game.toMenu(); window.WB.game.ui.showShop(); });
await page.waitForFunction(() => !!window.WB.game.account.me && !!window.WB.game.account.catalog, null, { timeout: 20000 });
const acc = await page.evaluate(() => ({ id: window.WB.game.account.me.id, owned: window.WB.game.account.me.owned.length, payments: window.WB.game.account.catalog.payments }));
ok(!!acc.id && acc.owned === 0, 'compte créé automatiquement à l’ouverture de la boutique', acc.id);
ok(acc.payments, 'paiements signalés actifs (clés de test locales)');
ok(await page.evaluate(() => document.querySelectorAll('.shop-card').length === 4), '4 produits affichés');
ok(await page.evaluate(() => /1,99\s€\sTTC/.test(document.querySelector('.shop-card .price')?.textContent || '')), 'prix TTC affiché', await page.evaluate(() => document.querySelector('.shop-card .price')?.textContent));
await page.evaluate(() => document.querySelector('[data-a="sel"][data-v="pack_fondateur"]').click());
await sleep(2500);
await page.screenshot({ path: SHOTS + 'boutique-pack.png' });
ok(await page.evaluate(() => !!document.getElementById('shop-preview')), 'page de détail avec aperçu 3D');
await page.evaluate(() => document.querySelector('[data-a="buy"]').click());
await sleep(400);
ok(await page.evaluate(() => !!document.getElementById('c-age') && !!document.getElementById('c-wd')), 'confirmation : âge et renonciation au droit de rétractation');
await page.evaluate(() => document.querySelector('[data-a="pay"]').click());
await sleep(300);
ok(await page.evaluate(() => location.search.includes('autotest')), 'paiement bloqué tant que les cases ne sont pas cochées');
await page.evaluate(() => document.querySelector('[data-a="cancel"]').click());

// confirmation de paiement simulée (webhook signé avec le secret de test local)
const ev = { id: 'evt_shop_' + Date.now(), type: 'checkout.session.completed', livemode: false, data: { object: { id: 'cs_test_shop_' + Date.now(), payment_status: 'paid', amount_total: 999, currency: 'eur', payment_intent: 'pi_shop_' + Date.now(), client_reference_id: acc.id, metadata: { sku: 'pack_fondateur', player: acc.id } } } };
const payload = JSON.stringify(ev), t = Math.floor(Date.now() / 1000);
const r = await fetch(API + '/api/stripe/webhook', { method: 'POST', body: payload, headers: { 'Content-Type': 'application/json', 'Stripe-Signature': `t=${t},v1=${createHmac('sha256', 'whsec_local_test_only').update(`${t}.${payload}`).digest('hex')}` } });
ok(r.status === 200, 'webhook de paiement accepté');
await page.evaluate(() => window.WB.game.account.refresh());
await page.evaluate(() => { const s = window.WB.game.ui; s.showShop(); });
await sleep(1500);
await page.evaluate(() => document.querySelector('[data-a="tab"][data-v="inv"]').click());
await sleep(500);
const inv = await page.evaluate(() => ({ owned: window.WB.game.account.me.owned, badge: window.WB.game.account.me.badge, rows: document.querySelectorAll('[data-a="equip"]').length }));
ok(inv.owned.length === 5 && inv.badge === 'FONDATEUR', 'inventaire : 5 objets et badge Fondateur', inv.owned.join(','));
await page.waitForSelector('[data-a="equip"][data-v="camo_fondateur"]', { timeout: 10000 });
await page.evaluate(() => document.querySelector('[data-a="equip"][data-v="camo_fondateur"]').click());
await page.waitForFunction(() => window.WB.game.account.me.equipped.camo === 'camo_fondateur', null, { timeout: 10000 }).then(() => ok(true, 'camouflage Fondateur équipé (enregistré sur le serveur)'), async () => ok(false, 'camouflage équipé', await page.evaluate(() => (document.getElementById('shop-status')?.textContent || '') + ' / ' + JSON.stringify(window.WB.game.account.me.equipped) + ' / boutons ' + document.querySelectorAll('[data-a="equip"]').length)));
await page.screenshot({ path: SHOTS + 'boutique-inventaire.png' });
await page.evaluate(() => document.querySelector('[data-a="tab"][data-v="hist"]').click());
await sleep(300);
ok(await page.evaluate(() => /Pack Fondateur/.test(document.querySelector('table.board')?.textContent || '') && /Payé/.test(document.querySelector('table.board')?.textContent || '')), 'historique : achat payé listé (mode test)');
await page.evaluate(() => document.querySelector('[data-a="close"]').click());
await page.evaluate(() => window.WB.game.startHub());
await page.waitForFunction(() => window.WB.state().level === 'hub' && window.WB.state().state === 'play', null, { timeout: 60000 });
await sleep(1500);
const camo = await page.evaluate(() => { let n = 0; window.WB.game.weapons.w.model.group.traverse((o) => { if (o.isMesh && o.material && o.material.map && o.material.map.isCanvasTexture) n++; }); return n; });
ok(camo > 0, 'camouflage appliqué au modèle de l’arme en vue subjective', `${camo} maillage(s)`);
const stats1 = await page.evaluate(() => { const s = window.WB.game.weapons.w.st; return { dmg: s.damage, rpm: s.rpm, spread: s.hipSpread, mag: s.mag }; });
ok(JSON.stringify(stats0) === JSON.stringify(stats1), 'aucun effet sur les statistiques de l’arme (dégâts, cadence, dispersion, chargeur)', JSON.stringify(stats1));
await page.evaluate(() => { window.WB.look(window.WB.game.player.yaw, 0.05); });
await sleep(800);
await page.screenshot({ path: SHOTS + 'arme-camo-fondateur.png' });
ok(await page.evaluate(() => { window.WB.game.toMenu(); return /FONDATEUR/.test(document.querySelector('.save-info')?.textContent || ''); }), 'badge visible sur le profil du menu principal');
ok(errors.length === 0, 'aucune erreur JavaScript', JSON.stringify(errors.slice(0, 3)));
console.log(`\n${pass} réussis, ${fail} échoués`);
await browser.close();
process.exit(fail ? 1 : 0);
